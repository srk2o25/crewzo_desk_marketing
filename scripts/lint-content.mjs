// Checks every content entry (posts, case studies, glossary terms) before each build (npm run prebuild).
//   Errors   = technical/portability rules (URLs, frontmatter, links, images, no MDX). They fail the build,
//              so the Netlify deploy preview for the Decap PR fails and the post can't be published.
//   Warnings = writing guidance (question headings, ~60-word answers, self-contained paragraphs). Printed
//              for the reviewer to judge; they never block publishing.
//
//   node scripts/lint-content.mjs                         lint every collection
//   node scripts/lint-content.mjs --dir <path>            lint another folder as posts
//   node scripts/lint-content.mjs --dir <path> --expect-fail   succeed only if errors are found (self-test)
import fs from 'fs'
import path from 'path'
import { unified } from 'unified'
import remarkParse from 'remark-parse'
import remarkGfm from 'remark-gfm'
import { visit } from 'unist-util-visit'
import { toString } from 'mdast-util-to-string'
import { ROOT, loadAuthors, readEntries } from '../lib/load.mjs'
import { COLLECTIONS, MAX_ANSWER_WORDS, RESERVED_SLUGS, SLUG_RE, wordCount } from '../lib/schema.mjs'

const args = process.argv.slice(2)
const dirArg = args.includes('--dir') ? args[args.indexOf('--dir') + 1] : null
const expectFail = args.includes('--expect-fail')

const MAX_PARAGRAPH_WORDS = 120
// Paragraphs opening with these usually lean on the previous paragraph and lose meaning when quoted alone.
const DANGLING_OPENERS = /^(this|that|these|those|it|they|he|she|also|as mentioned|as noted|as above|however|furthermore|moreover)\b/i
const SITE_HOSTS = /^https?:\/\/(www\.)?(crewzo\.co\.in)(\/|$)/i

const authors = loadAuthors()
// [collection, folder, entries]; with --dir, only that folder, treated as posts.
const targets = dirArg
  ? [['posts', path.resolve(ROOT, dirArg), readEntries('posts', path.resolve(ROOT, dirArg))]]
  : Object.entries(COLLECTIONS).map(([key, c]) => [key, path.join(ROOT, c.folder), readEntries(key)])
const seenDescriptions = new Map()
let errorCount = 0
let warningCount = 0

function lintEntry(collection, { file, slug, data, body, errors: schemaErrors }) {
  const isPost = collection === 'posts'
  const errors = schemaErrors.map((e) => `frontmatter ${e}`)
  const warnings = []
  const at = (node) => (node?.position ? ` (line ${node.position.start.line})` : '')

  // --- URL / file naming -------------------------------------------------------------------------
  if (!SLUG_RE.test(slug)) errors.push(`filename "${file}" must be lowercase letters, numbers and hyphens`)
  if (/^\d{4}-\d{2}(-\d{2})?-/.test(slug)) errors.push(`filename "${file}" must not start with a date`)
  if (data && data.slug !== slug) errors.push(`frontmatter slug "${data.slug}" must match the filename "${slug}"`)
  if (isPost && RESERVED_SLUGS.includes(slug)) errors.push(`slug "${slug}" is reserved for a section of the site`)

  if (data) {
    if ('author' in data && !authors[data.author]) errors.push(`author "${data.author}" has no content/authors/${data.author}.yml`)
    if (data.image && !fs.existsSync(path.join(ROOT, 'public', data.image))) errors.push(`image ${data.image} not found in public/`)
    const dupe = seenDescriptions.get(data.description)
    if (dupe) errors.push(`description duplicates ${dupe}`)
    seenDescriptions.set(data.description, file)
    const answerField = COLLECTIONS[collection].answerField
    const n = wordCount(data[answerField])
    if (n > MAX_ANSWER_WORDS) warnings.push(`${answerField} is ${n} words; aim for ${MAX_ANSWER_WORDS} or fewer`)
    for (const faq of data.faqs ?? []) {
      if (!faq.question.endsWith('?')) warnings.push(`FAQ "${faq.question}" should be phrased as a question`)
      const a = wordCount(faq.answer)
      if (a > MAX_ANSWER_WORDS) warnings.push(`FAQ answer to "${faq.question}" is ${a} words; aim for ${MAX_ANSWER_WORDS} or fewer`)
    }
  }

  // --- Portability: no MDX, shortcodes, wikilinks or embedded schema -----------------------------
  const lines = body.split('\n')
  let inFence = false
  lines.forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence
    if (inFence) return
    const where = ` (body line ${i + 1})`
    if (/^\s*(import|export)\s/.test(line)) errors.push(`MDX import/export is not allowed${where}`)
    if (/\{\{.*\}\}|\{%.*%\}/.test(line)) errors.push(`template shortcodes are not allowed${where}`)
    if (/\[\[[^\]]+\]\]/.test(line)) errors.push(`wikilinks are not allowed, use a normal [text](/path/) link${where}`)
    if (/<[A-Z][A-Za-z]*[\s/>]/.test(line)) errors.push(`JSX components are not allowed, use standard HTML${where}`)
    if (/^\s*:::/.test(line)) errors.push(`custom directives (:::) are not allowed${where}`)
    if (/<script\b/i.test(line)) errors.push(`<script> is not allowed; JSON-LD is generated by the page template${where}`)
  })

  // --- Writing guidance (warnings): question headings, ~60-word answers, self-contained paragraphs ---
  const tree = unified().use(remarkParse).use(remarkGfm).parse(body)
  const blocks = tree.children
  let hasList = false
  let hasTable = false
  let internalLinks = 0
  let externalLinks = 0

  blocks.forEach((node, i) => {
    if (node.type === 'heading') {
      const text = toString(node).trim()
      if (node.depth === 1) errors.push(`H1 not allowed in the body; the title is the H1${at(node)}`)
      if (node.depth === 2 || node.depth === 3) {
        if (!text.endsWith('?')) warnings.push(`H${node.depth} "${text}" isn't phrased as a reader's question${at(node)}`)
        const next = blocks[i + 1]
        if (!next || next.type !== 'paragraph') {
          warnings.push(`H${node.depth} "${text}" isn't followed directly by a short answer paragraph${at(node)}`)
        } else {
          const n = wordCount(toString(next))
          if (n > MAX_ANSWER_WORDS) warnings.push(`answer under "${text}" is ${n} words; aim for ${MAX_ANSWER_WORDS} or fewer${at(next)}`)
        }
      }
    }
    if (node.type === 'paragraph') {
      const text = toString(node).trim()
      const n = wordCount(text)
      if (n > MAX_PARAGRAPH_WORDS) warnings.push(`paragraph is ${n} words; split it so each block stands alone${at(node)}`)
      if (DANGLING_OPENERS.test(text)) warnings.push(`paragraph opens with "${text.split(/\s+/)[0]}", which may not make sense out of context${at(node)}`)
    }
    if (node.type === 'list') hasList = true
    if (node.type === 'table') hasTable = true
  })

  visit(tree, (node) => {
    if (node.type === 'image') {
      if (!node.alt?.trim()) errors.push(`image ${node.url} needs alt text${at(node)}`)
      if (!/^\/images\/blog\//.test(node.url)) errors.push(`image ${node.url} must live under /images/blog/${at(node)}`)
      else if (!fs.existsSync(path.join(ROOT, 'public', node.url))) errors.push(`image ${node.url} not found in public/${at(node)}`)
    }
    if (node.type === 'link') {
      const url = node.url
      if (SITE_HOSTS.test(url)) {
        errors.push(`link to our own site must be relative (e.g. /features/), not ${url}${at(node)}`)
      } else if (url.startsWith('/')) {
        internalLinks++
        const pathname = url.split(/[?#]/)[0]
        if (!pathname.endsWith('/') && !/\.[a-z0-9]+$/i.test(pathname)) errors.push(`internal link ${url} must end with a trailing slash${at(node)}`)
        if (pathname !== pathname.toLowerCase()) errors.push(`internal link ${url} must be lowercase${at(node)}`)
      } else if (/^https?:\/\//.test(url)) {
        externalLinks++
        if (url.startsWith('http://')) errors.push(`external link ${url} must use https${at(node)}`)
      } else if (!url.startsWith('#') && !url.startsWith('mailto:')) {
        errors.push(`link "${url}" must be root-relative (/path/) or absolute https${at(node)}`)
      }
    }
  })

  if (isPost) {
    if (internalLinks === 0) warnings.push('no internal links: link to a related Crewzo Desk page or post')
    if (externalLinks === 0) warnings.push('no external links: consider linking a source inline for any facts or figures')
    if (!hasList && !hasTable) warnings.push('no list or table: add structured, factual detail')
  }

  return { errors, warnings }
}

let entryCount = 0
const seenIds = new Map() // permanent IDs must be unique across every content type
for (const [collection, folder, entries] of targets) {
  if (collection === 'posts' && !entries.length) {
    console.error(`No .md files found in ${path.relative(ROOT, folder) || folder}`)
    process.exit(1)
  }
  const seenSlugs = new Set()
  for (const entry of entries) {
    const { errors, warnings } = lintEntry(collection, entry)
    if (entry.data) {
      if (seenSlugs.has(entry.data.slug)) errors.push(`slug "${entry.data.slug}" is used by another ${COLLECTIONS[collection].label}`)
      seenSlugs.add(entry.data.slug)
      const owner = seenIds.get(entry.data.id)
      if (owner) errors.push(`id ${entry.data.id} is already used by ${owner}`)
      seenIds.set(entry.data.id, entry.file)
    }
    const rel = path.relative(ROOT, path.join(folder, entry.file))
    if (!errors.length && !warnings.length) console.log(`✓ ${rel}`)
    for (const e of errors) console.log(`✗ ${rel}: ${e}`)
    for (const w of warnings) console.log(`! ${rel}: ${w}`)
    errorCount += errors.length
    warningCount += warnings.length
    entryCount++
  }
}

console.log(`
${entryCount} entr${entryCount === 1 ? 'y' : 'ies'}, ${errorCount} error(s), ${warningCount} warning(s)`)

if (expectFail) {
  if (errorCount === 0) {
    console.error('Expected the lint to find errors in these fixtures, but it found none.')
    process.exit(1)
  }
  console.log('Self-test passed: the lint rejected the bad fixtures.')
  process.exit(0)
}
process.exit(errorCount ? 1 : 0)
